#!/usr/bin/env bash
# Assemble the Hugging Face Space folder of the FedRAG API (the public demo) from this repository:
#
#   scripts/build_hf_space.sh [OUT_DIR]        (or: make space-bundle)
#
# OUT_DIR defaults to deploy/build/hf-space (git-ignored) and is replaced on every run. It is
# self-contained: `docker build OUT_DIR` builds the image, and its contents are what the Space's
# repository holds (deploy/README.md: upload with `hf upload` or a git push). It contains:
#
#   Dockerfile, .dockerignore, README.md   deploy/hf-space/ (the README carries the Space's YAML)
#   LICENSE
#   backend/app/                           the API's code (no __pycache__)
#   backend/constraints.txt                the pinned versions
#   backend/requirements.txt               generated from backend/pyproject.toml's dependencies
#   data/eval/*.json, stance_gold.jsonl    tracked results: benchmarks, recorded example answers,
#                                          the stance reference labels
#   data/index/chunks.jsonl, manifest.json the search index's passages (evaluation drilldowns)
#
# and never: data/chroma, data/models, data/eval_cache, data/raw, data/processed, .env files.
# Before finishing it checks that no file holds an OpenAI-style key, a Neon-style password, a
# Postgres URL with a password, or the OPENAI_API_KEY and DATABASE_URL values in backend/.env
# (compared in memory, never printed).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/deploy/build/hf-space}"
SPACE_SRC="$ROOT/deploy/hf-space"
if [ -x "$ROOT/backend/.venv/bin/python" ]; then PYTHON="$ROOT/backend/.venv/bin/python"; else PYTHON=python3; fi

fail() { echo "build_hf_space: $*" >&2; exit 1; }

# What the demo serves must exist before anything is copied.
need=(
  "data/eval/rag_benchmark.json:make rag-eval-report"
  "data/eval/ask_examples.json:make ask-examples"
  "data/eval/stance_benchmark.json:make stance-benchmark"
  "data/eval/stance_gold.jsonl:the tracked stance reference labels"
  "data/index/chunks.jsonl:make index"
  "data/index/manifest.json:make index"
)
for item in "${need[@]}"; do
  file="${item%%:*}"
  [ -f "$ROOT/$file" ] || fail "$file is missing (${item#*:})."
done
case "$OUT" in
  "$ROOT" | "$ROOT/" | "$ROOT/backend"* | "$ROOT/data"* | "$ROOT/frontend"* | "$SPACE_SRC"*)
    fail "refusing to write into $OUT: pick an empty or build directory." ;;
esac
# OUT is deleted and rebuilt, so it must be new, empty, or a previous Space folder (a mistyped
# argument such as a home directory is refused, not wiped).
if [ -e "$OUT" ] && [ -n "$(ls -A "$OUT" 2>/dev/null)" ]; then
  [ -f "$OUT/Dockerfile" ] && [ -f "$OUT/README.md" ] && [ -d "$OUT/backend/app" ] \
    || fail "refusing to replace $OUT: it is not empty and is not a Space folder built by this script."
fi

rm -rf "$OUT"
mkdir -p "$OUT/backend" "$OUT/data/eval" "$OUT/data/index"

cp "$SPACE_SRC/Dockerfile" "$SPACE_SRC/README.md" "$SPACE_SRC/.dockerignore" "$ROOT/LICENSE" "$OUT/"
(cd "$ROOT/backend" && tar --exclude='__pycache__' --exclude='*.py[cod]' --exclude='.DS_Store' -cf - app) \
  | (cd "$OUT/backend" && tar -xf -)
cp "$ROOT/backend/constraints.txt" "$OUT/backend/"
"$PYTHON" - "$ROOT/backend/pyproject.toml" "$OUT/backend/requirements.txt" <<'PY'
import sys
import tomllib

with open(sys.argv[1], "rb") as f:
    dependencies = tomllib.load(f)["project"]["dependencies"]
header = (
    "# Generated by scripts/build_hf_space.sh from backend/pyproject.toml [project.dependencies].\n"
    "# Installed with -c constraints.txt: every version is the one the repository pins.\n"
)
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write(header + "".join(f"{d}\n" for d in dependencies))
PY
cp "$ROOT"/data/eval/*.json "$ROOT/data/eval/stance_gold.jsonl" "$OUT/data/eval/"
cp "$ROOT/data/index/chunks.jsonl" "$ROOT/data/index/manifest.json" "$OUT/data/index/"

# Nothing secret may leave this machine. backend/.env's values are compared in memory only.
if find "$OUT" -name '.env*' ! -name '.env.example' | grep -q .; then
  fail "an .env file ended up in $OUT."
fi
"$PYTHON" - "$OUT" "$ROOT/backend/.env" <<'PY' || fail "a secret-looking value is in the bundle (see above); nothing was uploaded."
import re
import sys
from pathlib import Path

out, env_file = Path(sys.argv[1]), Path(sys.argv[2])
patterns = {
    "an OpenAI-style API key": re.compile(rb"sk-[A-Za-z0-9_-]{32,}"),
    "a Neon password": re.compile(rb"npg_[A-Za-z0-9]{8,}"),
    "a Postgres URL with a password": re.compile(
        rb"postgres(?:ql)?://[^\s:/@\"']+:(?!PASSWORD@|secret@|fedrag@)[^\s@\"'<]{6,}@"
    ),
}
secrets = []
if env_file.is_file():
    for line in env_file.read_text(encoding="utf-8").splitlines():
        name, sep, value = line.partition("=")
        value = value.strip().strip("'\"")
        if sep and name.strip() in {"OPENAI_API_KEY", "DATABASE_URL"} and len(value) >= 8:
            secrets.append((name.strip(), value.encode()))
found = False
for path in sorted(p for p in out.rglob("*") if p.is_file()):
    data = path.read_bytes()
    for what, pattern in patterns.items():
        if pattern.search(data):
            print(f"  {path.relative_to(out)}: {what}", file=sys.stderr)
            found = True
    for name, value in secrets:
        if value in data:
            print(f"  {path.relative_to(out)}: the value of {name} in backend/.env", file=sys.stderr)
            found = True
sys.exit(1 if found else 0)
PY

files=$(find "$OUT" -type f | wc -l | tr -d ' ')
size=$(du -sh "$OUT" | cut -f1)
largest=$(find "$OUT" -type f -exec du -k {} + | sort -rn | awk 'NR == 1 {printf "%.1f MB", $1 / 1024}')
shown="${OUT#"$ROOT"/}"  # relative to the repository root when it is inside it
echo "Space folder ready: $shown ($files files, $size; largest file $largest)."
echo "  Build and run it locally: docker build -t fedrag-space \"$shown\" && docker run --rm -p 127.0.0.1:7860:7860 --env-file ~/.fedrag-space.env fedrag-space   (deploy/README.md)"
echo "  Upload it to the Space:   backend/.venv/bin/hf upload <user>/<space> \"$shown\" . --repo-type space   (deploy/README.md)"
